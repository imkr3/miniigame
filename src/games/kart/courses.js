/** 설계 → 트랙 데이터 일부 (제어점, 점프대·글라이더·고가도로 번호) */
export function fromCourse(id) {
  const D = DESIGNS[id], c = course(D.cmds, D.h0 ?? 0), M = c.marks;
  return {
    points: c.points, scale: 1,
    ramps: (D.ramps ?? []).map((m) => M[m]),
    gliders: (D.gliders ?? []).map(([a, b]) => [M[a], M[b]]),
    bridges: (D.bridges ?? []).map(([a, b]) => [M[a], M[b]]),
  };
}
